export function getTraditionalVerdicts(
  symbol: XiaoLiurenSymbol,
  category: TraditionalVerdictCategory,
): TraditionalVerdict[] {
  const [trend, advice] = traditionalVerdictGuidance[category][symbol]
  return traditionalVerdictSummaries[category][symbol].map((summary) => ({ summary, trend, advice }))
}
